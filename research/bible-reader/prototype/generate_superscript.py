#!/usr/bin/env python3
"""Sparse private verse-number font; preserve the original eight baseline shifts."""
from pathlib import Path
DIGITS=((31,17,31),(18,31,16),(29,21,23),(21,21,31),(7,4,31),(23,21,29),(31,21,29),(1,1,31),(31,21,31),(23,21,31))
def generate():
 lines=['/* Generated by generate_superscript.py. Unused glyphs have zero width.', ' * One blank slot and ten 32-byte digit slots per height band. Shared maps', ' * retain native character codes 0x90..0x99; no reserved control codes. */', 'static const uint8_t superscript_widths[256]={']
 lines +=[f' [0x{0x90+d:02x}]=4,'for d in range(10)];lines+=['};','static const uint16_t superscript_offsets[256]={']
 lines +=[f' [0x{0x90+d:02x}]={32*(d+1)},'for d in range(10)];lines+=['};','static const uint8_t superscript_bitmaps[8][11*32]={']
 for band in range(8):
  lines.append(' {');shift=2*(band+1)-1
  for digit,cols in enumerate(DIGITS):
   entries=[]
   for x,col in enumerate(cols):
    value=col<<shift
    for page in range(8):
     byte=(value>>(8*page))&255
     if byte:entries.append(f'[{32*(digit+1)+4*page+x}]={byte}')
   lines.append('  '+', '.join(entries)+',')
  lines.append(' },')
 lines+=['};',''];return '\n'.join(lines)
if __name__=='__main__':Path(__file__).with_name('Superscript.h').write_text(generate())
